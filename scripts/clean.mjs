import { lstat, readdir, rm } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

// Only known generated destinations: source directories named build/ are tools.
const outputs = [
  '_site', 'progetti/slide/dist',
  'progetti/slide/.slidev', 'progetti/slide/slides-export',
  'progetti/slide/node_modules/.slidev', 'progetti/slide/node_modules/.vite-temp',
  'progetti/slide/public/images/shared', 'progetti/slide/public/audio/lezione-griglie',
  'progetti/booklet/main.pdf', 'progetti/booklet/build/booklet.pdf',
  ...['aperture', '00-frontespizio-indice', '01-storia-del-design', '02-ricerca',
    '03-accessibilita', '04-gestalt', '05-colore', '06-tipografia', '07-griglia']
    .map(name => `progetti/booklet/build/anteprime/${name}.pdf`),
  '.impeccable/hook.cache.json',
]
const evidence = ['reports', 'progetti/booklet/build/verifiche',
  '.impeccable/review', '.impeccable/critique',
  ...['home', 'slide', 'booklet', 'caffe-ttc', 'ilmeteo']
    .flatMap(project => ['review', 'critique'].map(name => `progetti/${project}/.impeccable/${name}`))]
const toolDirectories = ['scripts', ...['home', 'slide', 'booklet', 'caffe-ttc', 'ilmeteo']
  .map(project => `progetti/${project}/scripts`)]

/** Remove reproducible output; preserve every report, source, original and archive. */
export async function cleanProject(root, { dryRun = false, keepDev = false } = {}) {
  root = path.resolve(root)
  const removed = new Set()
  const skippedSymlinks = new Set()
  let removedBytes = 0, removedFiles = 0
  async function info(relative) {
    try { return await lstat(path.join(root, relative)) }
    catch (error) { if (error.code === 'ENOENT') return null; throw error }
  }
  // A symbolic-link ancestor could redirect a deletion outside the checkout.
  async function safePath(relative) {
    const parts = relative.split('/')
    for (let index = 1; index <= parts.length; index++) {
      const current = parts.slice(0, index).join('/')
      const entry = await info(current)
      if (!entry) return false
      if (entry.isSymbolicLink()) { skippedSymlinks.add(current); return false }
    }
    return true
  }
  async function measure(relative) {
    const entry = await info(relative)
    if (entry.isDirectory()) {
      for (const child of await readdir(path.join(root, relative))) await measure(`${relative}/${child}`)
    } else { removedBytes += entry.size; removedFiles++ }
  }
  async function remove(relative) {
    if (!await safePath(relative)) return
    await measure(relative)
    if (!dryRun) await rm(path.join(root, relative), { recursive: true, force: true })
    removed.add(relative)
  }
  for (const relative of outputs) {
    if (keepDev && (relative.includes('/.slidev') || relative.endsWith('/.vite-temp') || relative.startsWith('progetti/slide/public/'))) continue
    await remove(relative)
  }
  // Python caches in tool folders contain generated bytecode, not retained assets.
  // Other files inside a cache directory are deliberately preserved.
  async function pruneBytecode(relative) {
    const entry = await info(relative)
    if (!entry || entry.isSymbolicLink() || !entry.isDirectory() || !await safePath(relative)) return
    for (const child of await readdir(path.join(root, relative), { withFileTypes: true })) {
      const current = `${relative}/${child.name}`
      if (child.isSymbolicLink()) continue
      if (child.isDirectory()) {
        if (['reports', 'archive', 'archivio', 'originals', 'originali', 'node_modules', '.venv'].includes(child.name)) continue
        await pruneBytecode(current)
      } else if (path.basename(relative) === '__pycache__' && /\.py[co]$/.test(child.name)) await remove(current)
    }
    if (path.basename(relative) === '__pycache__') {
      const remaining = (await readdir(path.join(root, relative))).filter(name => !removed.has(`${relative}/${name}`))
      if (!remaining.length) {
        if (!dryRun) await rm(path.join(root, relative), { recursive: true })
        removed.add(relative)
      }
    }
  }
  for (const relative of toolDirectories) await pruneBytecode(relative)
  const preservedReports = []
  for (const relative of evidence) if (await info(relative)) preservedReports.push(relative)
  return { dryRun, removedFiles, removedBytes, removedPaths: [...removed],
    preservedReports, skippedSymlinks: [...skippedSymlinks] }
}

