import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { readFile } from 'node:fs/promises'
import { examples } from '../../data/esercitazioni/framework-curriculum.mjs'
import { renderNativeDocument } from '../../data/esercitazioni/native-examples.mjs'
import { chromium } from 'playwright-chromium'
import { checkExerciseSources } from './exercise-sources.mjs'

const report = { sources: await checkExerciseSources(), checks: [], errors: [] }
const browser = await chromium.launch()
const baseCSS = await readFile('assets/esercitazioni/tailwind-daisyui/render.css', 'utf8')
const customCSS = await readFile('assets/esercitazioni/tailwind-daisyui/custom.css', 'utf8')
try {
  const page = await browser.newPage({ viewport: { width: 1000, height: 420 } })
  page.on('pageerror', error => report.errors.push(error.message))
  const go = example => page.setContent(renderNativeDocument(examples[example], baseCSS, customCSS))
  await go('buttons')
  assert.equal(await page.getByRole('button', { name: 'Non disponibile' }).isDisabled(), true)
  report.checks.push('disabled button is native')
  await go('form')
  const name = page.getByLabel('Nome e cognome', { exact: true }), email = page.getByLabel('Email', { exact: true })
  assert.equal(await email.evaluate(node => node.checkValidity()), false)
  await page.getByRole('button', { name: 'Iscriviti', exact: true }).click()
  assert.equal(await page.getByRole('status').textContent(), '', 'invalid data must not produce a success message')
  await name.fill('Esempio didattico')
  await email.fill('studente@example.org')
  assert.equal(await email.evaluate(node => node.checkValidity()), true)
  await page.getByRole('button', { name: 'Iscriviti', exact: true }).click()
  assert.equal(await page.getByRole('status').textContent(), 'Dati ricevuti nell’esempio locale.')
  assert.ok(await page.locator('main').evaluate(node => node.scrollHeight <= 396), 'submitted form fits its example viewport')
  report.checks.push('visible labels, native constraints and announced local confirmation')
  await go('validation')
  assert.equal(await page.getByLabel('Email', { exact: true }).getAttribute('aria-invalid'), 'true')
  assert.equal(await page.getByLabel('Email', { exact: true }).getAttribute('aria-describedby'), 'email-errore')
  assert.ok((await page.locator('#email-errore').textContent()).includes('nome@esempio.it'))
  report.checks.push('error is linked to the input and gives a correction')
  await go('selection')
  await page.getByLabel('Scegli un turno').selectOption({ label: 'Pomeriggio' })
  await page.getByLabel('Ricevi il promemoria').uncheck()
  assert.equal(await page.getByLabel('Ricevi il promemoria').isChecked(), false)
  report.checks.push('native select and checkbox work independently')
  await go('dropdown')
  await page.locator('summary').focus()
  await page.keyboard.press('Enter')
  assert.equal(await page.locator('details').evaluate(node => node.open), false)
  await page.keyboard.press('Enter')
  assert.equal(await page.locator('details').evaluate(node => node.open), true)
  report.checks.push('disclosure opens and closes from the keyboard')
  await go('modal')
  assert.equal(await page.locator('dialog').evaluate(node => node.open), false, 'entering the slide must not open a modal')
  await page.getByRole('button', { name: 'Apri', exact: true }).focus()
  await page.keyboard.press('Enter')
  const dialog = page.getByRole('dialog', { name: 'Posto prenotato' })
  await dialog.waitFor()
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('dialog').evaluate(node => node.open), false)
  assert.equal(await page.getByRole('button', { name: 'Apri', exact: true }).evaluate(node => document.activeElement === node), true)
  await page.emulateMedia({ media: 'print' })
  await page.waitForFunction(() => document.querySelector('dialog').open)
  await page.emulateMedia({ media: 'screen' })
  await page.waitForFunction(() => !document.querySelector('dialog').open)
  report.checks.push('dialog opens on request, Escape restores focus and print retains its contents')
  report.contrast = []
  for (const example of ['colors', 'validation', 'buttons', 'themes', 'composedEvent', 'actionAndLink', 'messageStates']) {
    await go(example)
    const nodes = page.locator('button:not(:disabled), a.btn, .text-error, .alert > span')
    for (const node of await nodes.all()) {
      for (const state of ['rest', 'hover']) {
        if (state === 'hover') await node.hover()
        await node.evaluate(node => Promise.all(node.getAnimations().filter(animation => Number.isFinite(animation.effect?.getComputedTiming().endTime)).map(animation => animation.finished.catch(() => {}))))
        const measurement = await node.evaluate(node => {
          const context = document.createElement('canvas').getContext('2d', { willReadFrequently: true })
          const rgb = color => { context.clearRect(0, 0, 1, 1); context.fillStyle = color; context.fillRect(0, 0, 1, 1); return [...context.getImageData(0, 0, 1, 1).data] }
          const luminance = color => color.slice(0, 3).map(value => { const v = value / 255; return v <= .04045 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4 }).reduce((sum, value, i) => sum + value * [.2126, .7152, .0722][i], 0)
          let background = [255, 255, 255]
          const ancestors = []; for (let n = node; n; n = n.parentElement) ancestors.unshift(n)
          for (const element of ancestors) { const c = rgb(getComputedStyle(element).backgroundColor), alpha = c[3] / 255; background = background.map((v, i) => c[i] * alpha + v * (1 - alpha)) }
          const foreground = rgb(getComputedStyle(node).color), alpha = foreground[3] / 255
          const text = foreground.slice(0, 3).map((value, i) => value * alpha + background[i] * (1 - alpha))
          const values = [luminance(text), luminance(background)].sort((a, b) => b - a)
          return { text: node.textContent.trim(), ratio: (values[0] + .05) / (values[1] + .05) }
        })
        report.contrast.push({ example, state, ...measurement })
      }
      await page.mouse.move(0, 0)
    }
  }
  assert.ok(report.contrast.every(item => item.ratio >= 4.5), `Text contrast below 4.5: ${JSON.stringify(report.contrast.filter(item => item.ratio < 4.5))}`)
  report.checks.push('text/background pairs in the revised examples reach 4.5:1 at rest and on hover')
  await go('themes')
  const backgrounds = await page.locator('[data-theme] section, section[data-theme]').evaluateAll(nodes => nodes.map(node => getComputedStyle(node).backgroundColor))
  assert.equal(backgrounds.length, 2)
  assert.notEqual(backgrounds[0], backgrounds[1])
  report.checks.push('light and dark sections use distinct semantic surfaces')
  await go('responsive')
  const wide = page.locator('iframe[title="Viewport ampio"]').contentFrame()
  const narrow = page.locator('iframe[title="Viewport stretto"]').contentFrame()
  const columns = async frame => frame.locator('main > div').evaluate(node => getComputedStyle(node).gridTemplateColumns.split(' ').length)
  assert.equal(await columns(wide), 2)
  assert.equal(await columns(narrow), 1)
  report.checks.push('the same Grid changes from two columns to one at a real narrow viewport')
  await go('actionAndLink')
  await page.getByRole('button', { name: 'Salva la bozza', exact: true }).click()
  assert.equal(await page.getByRole('status').textContent(), 'Bozza salvata (demo).')
  assert.equal(await page.getByRole('link', { name: 'Vai al programma', exact: true }).getAttribute('href'), '#programma')
  assert.equal(await page.locator('#programma').count(), 1)
  report.checks.push('worked action updates a live result and the destination has a real target')
  await go('exclusiveChoices')
  await page.getByRole('radio', { name: 'Pomeriggio', exact: true }).check()
  assert.equal(await page.getByRole('radio', { name: 'Mattina', exact: true }).isChecked(), false)
  await page.getByRole('checkbox', { name: 'Slide', exact: true }).check()
  await page.getByRole('checkbox', { name: 'Esercizi', exact: true }).check()
  assert.equal(await page.locator('input[type=checkbox]:checked').count(), 2)
  report.checks.push('the worked radio group is exclusive while the two checkboxes stay independent')
  await go('faqChoices')
  for (const summary of await page.locator('summary').all()) { await summary.focus(); await page.keyboard.press('Enter') }
  assert.equal(await page.locator('details[open]').count(), 2)
  assert.ok(await page.locator('main').evaluate(node => node.scrollHeight <= 396), 'both open answers fit')
  report.checks.push('both worked disclosures can open from the keyboard and stay inside the example')
  await go('typeHierarchy')
  const typography = await page.locator('h2').evaluateAll(nodes => nodes.map(node => ({ size: parseFloat(getComputedStyle(node).fontSize), weight: getComputedStyle(node).fontWeight })))
  assert.ok(typography[1].size > typography[0].size && Number(typography[1].weight) > Number(typography[0].weight), 'the declared utility typography is actually applied')
  const spacing = await page.locator('section > p').evaluateAll(nodes => nodes.map(node => parseFloat(getComputedStyle(node).marginTop)))
  assert.ok(spacing[1] > spacing[0], 'renderer resets must not override Tailwind margins')
  report.checks.push('worked typography and spacing have visibly different computed values')
  await go('spacingCompare')
  const boxHeights = await page.locator('section > p:first-child').evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().height))
  assert.ok(Math.abs(boxHeights[0] - boxHeights[1]) < 1, 'grid stretching must not change equal child padding in the spacing comparison')
  report.checks.push('the padding/gap comparison preserves equal child boxes without grid stretching')
  await go('gridSpans')
  const spans = await page.locator('main > div').evaluate(grid => ({ columns: getComputedStyle(grid).gridTemplateColumns.split(' ').length, header: grid.querySelector('header').getBoundingClientRect().width, side: grid.querySelector('aside').getBoundingClientRect().width, content: grid.querySelector('section').getBoundingClientRect().width, grid: grid.getBoundingClientRect().width }))
  assert.equal(spans.columns, 3)
  assert.equal(spans.header, spans.grid)
  assert.ok(spans.content > spans.side * 2)
  report.checks.push('the worked Grid spans a full header and a two-column content area')
  await go('inheritedSpacing')
  const inherited = await page.locator('article').evaluateAll(nodes => nodes.map(node => parseFloat(getComputedStyle(node).paddingTop)))
  assert.equal(inherited[0], inherited[1] * 3)
  await go('fallbackColor')
  assert.notEqual(...await page.locator('.campione').evaluateAll(nodes => nodes.map(node => getComputedStyle(node).backgroundColor)))
  report.checks.push('local variables override inherited values and fallback surfaces differ')
  await go('themeSwitch')
  const surface = page.locator('main > div')
  const light = await surface.evaluate(node => getComputedStyle(node).backgroundColor)
  await page.getByRole('checkbox', { name: 'Tema scuro', exact: true }).check()
  const dark = await surface.evaluate(node => getComputedStyle(node).backgroundColor)
  assert.notEqual(light, dark)
  await page.getByRole('checkbox', { name: 'Tema scuro', exact: true }).uncheck()
  assert.equal(await surface.evaluate(node => getComputedStyle(node).backgroundColor), light)
  report.checks.push('the worked theme controller changes the actual surface and restores it')
  await go('radiusCompare')
  const radii = await page.locator('article').evaluateAll(nodes => nodes.map(node => parseFloat(getComputedStyle(node).borderTopLeftRadius)))
  assert.equal(radii[0], 0)
  assert.ok(radii[1] > radii[0])
  await go('responsiveVisibility')
  const wideVisibility = page.locator('iframe[title="Viewport ampio"]').contentFrame()
  const narrowVisibility = page.locator('iframe[title="Viewport stretto"]').contentFrame()
  assert.equal(await wideVisibility.getByText('Aula 12 · porta computer e prototipo.', { exact: true }).isVisible(), true)
  assert.equal(await narrowVisibility.getByText('Aula 12 · porta computer e prototipo.', { exact: true }).isVisible(), false)
  assert.equal(await narrowVisibility.getByText('Apri il programma per i dettagli.', { exact: true }).isVisible(), true)
  report.checks.push('radius tokens change the card geometry and responsive visibility changes in real viewports')
  assert.deepEqual(report.errors, [])
  report.status = 'passed'
} finally {
  await browser.close()
  await mkdir('reports/frameworks', { recursive: true })
  await writeFile('reports/frameworks/examples-check.json', JSON.stringify(report, null, 2) + '\n')
}
console.log(JSON.stringify(report, null, 2))
